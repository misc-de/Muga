def test_an_edited_photo_gets_a_new_thumbnail(thumbnailer: Thumbnailer, photo: Path) -> None:
    """The case the user hits: rotate or edit a photo, and the grid tile has to
    turn with it instead of showing the old orientation."""
    first = thumbnailer.ensure_thumbnail(photo, "image")
    assert first is not None
    assert PILImage.open(first).size[0] > PILImage.open(first).size[1]

    _make_image(photo, PORTRAIT, (30, 30, 200))
    _shift_mtime(photo, 10.0)

    second = thumbnailer.ensure_thumbnail(photo, "image")
    assert second == first, "the thumbnail keeps its deterministic path"
    regenerated = PILImage.open(second)
    assert regenerated.size[1] > regenerated.size[0], "still showing the pre-edit image"


def test_an_unchanged_photo_reuses_its_thumbnail(
    thumbnailer: Thumbnailer, photo: Path,
) -> None:
    """The freshness check must not turn every scan into a full re-decode of the
    library — that is the whole point of the cache."""
    thumbnailer.ensure_thumbnail(photo, "image")

    with patch.object(
        Thumbnailer, "_image_thumbnail", autospec=True,
    ) as decode:
        assert thumbnailer.ensure_thumbnail(photo, "image") is not None
    decode.assert_not_called()


def test_a_thumbnail_from_before_stamping_is_kept(
    thumbnailer: Thumbnailer, photo: Path,
) -> None:
    """Thumbnails generated by an older Muga carry their generation time, which
    is later than the source's. Treating those as stale would re-decode every
    photo on the first launch after an upgrade."""
    target = thumbnailer.thumb_path_for(photo)
    thumbnailer.ensure_thumbnail(photo, "image")
    _touch(target, photo.stat().st_mtime + 500)

    with patch.object(Thumbnailer, "_image_thumbnail", autospec=True) as decode:
        thumbnailer.ensure_thumbnail(photo, "image")
    decode.assert_not_called()


def test_an_unreadable_source_keeps_its_cached_thumbnail(
    thumbnailer: Thumbnailer, photo: Path,
) -> None:
    """An unmounted drive or a permission change leaves nothing to regenerate
    from, so the cached thumbnail is the best answer available — a stale tile
    beats a blank one."""
    first = thumbnailer.ensure_thumbnail(photo, "image")
    photo.unlink()

    assert thumbnailer.ensure_thumbnail(photo, "image") == first


def test_stamping_leaves_atime_alone(thumbnailer: Thumbnailer, photo: Path) -> None:
    """The disk-cache evictor sorts by atime (LRU). Stamping the mtime must not
    disturb that ordering, or eviction would start dropping the wrong files."""
    target = thumbnailer.thumb_path_for(photo)
    thumbnailer.ensure_thumbnail(photo, "image")

    stat = target.stat()
    assert stat.st_mtime == pytest.approx(photo.stat().st_mtime, abs=1e-3)
    # A file written moments ago has its atime at (or after) its creation, not
    # dragged back to the source's timestamp.
    assert stat.st_atime > photo.stat().st_mtime - 1


def test_a_video_thumbnail_is_stamped_too(
    thumbnailer: Thumbnailer, tmp_path: Path,
) -> None:
    """The video branch goes through an external thumbnailer rather than
    Pillow, so it needs the same stamp — otherwise a re-encoded clip keeps its
    old frame. Driven through a stub so the test needs no ffmpeg."""
    clip = tmp_path / "clip.mp4"
    clip.write_bytes(b"not really a video")
    target = thumbnailer.thumb_path_for(clip)

    def _fake_video(self, path: Path, dest: Path) -> str:
        _make_image(dest, LANDSCAPE, (10, 10, 10))
        return str(dest)

    with patch.object(Thumbnailer, "_video_thumbnail", autospec=True, side_effect=_fake_video):
        assert thumbnailer.ensure_thumbnail(clip, "video") == str(target)

    assert target.stat().st_mtime == pytest.approx(clip.stat().st_mtime, abs=1e-3)


def test_invalidate_forces_a_regeneration(thumbnailer: Thumbnailer, photo: Path) -> None:
    """The exact guarantee, for callers that cannot depend on timestamps — two
    rotations saved inside a single filesystem timestamp tick, say."""
    thumbnailer.ensure_thumbnail(photo, "image")
    target = thumbnailer.thumb_path_for(photo)
    assert target.exists()

    thumbnailer.invalidate(photo)

    assert not target.exists()
    with patch.object(Thumbnailer, "_image_thumbnail", autospec=True) as decode:
        thumbnailer.ensure_thumbnail(photo, "image")
    decode.assert_called_once()


def test_invalidate_is_quiet_about_a_thumbnail_that_is_not_there(
    thumbnailer: Thumbnailer, photo: Path,
) -> None:
    thumbnailer.invalidate(photo)  # must not raise


