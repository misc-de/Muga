DAV = "/remote.php/dav/files/alice/Photos/holiday.jpg"


@pytest.fixture()
def nc_client(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    monkeypatch.setattr(nc, "_NC_THUMB", tmp_path / "nc-thumbs")
    monkeypatch.setattr(nc, "_NC_CACHE", tmp_path / "nc-cache")
    return nc.NextcloudClient("https://cloud.example.org", "alice", "app-password")


class _Response:
    """Stands in for http.client.HTTPResponse."""

    def __init__(self, body: bytes, status: int = 200) -> None:
        self.status = status
        self._body = body
        self._read = False

    def getheader(self, name, default=None):
        return {"Content-Length": str(len(self._body))}.get(name, default)

    def read(self, size=None):
        if self._read:
            return b""
        self._read = True
        return self._body


def _serving(client, body: bytes):
    """Patch *client*'s connections so any request answers with *body*."""
    conn = MagicMock()
    conn.getresponse.side_effect = lambda: _Response(body)
    return patch.multiple(
        client,
        _persistent_conn=MagicMock(return_value=conn),
        _conn=MagicMock(return_value=conn),
    )


def test_a_downloaded_thumbnail_carries_the_server_time(nc_client) -> None:
    """Stamping with the server's mtime rather than the download time is what
    makes the comparison immune to clock skew: a server running minutes ahead
    would otherwise make every entry look stale on every sweep."""
    with _serving(nc_client, b"thumb-bytes"):
        local = nc_client.ensure_thumbnail(DAV, remote_mtime=1_700_000_000.0)

    assert local is not None
    assert Path(local).stat().st_mtime == pytest.approx(1_700_000_000.0, abs=1e-3)


def test_a_file_replaced_on_the_server_is_fetched_again(nc_client) -> None:
    with _serving(nc_client, b"old-thumb"):
        first = nc_client.ensure_thumbnail(DAV, remote_mtime=1_700_000_000.0)
    assert Path(first).read_bytes() == b"old-thumb"

    with _serving(nc_client, b"new-thumb"):
        second = nc_client.ensure_thumbnail(DAV, remote_mtime=1_700_000_900.0)

    assert second == first
    assert Path(second).read_bytes() == b"new-thumb"


def test_an_unchanged_server_file_is_served_from_cache(nc_client) -> None:
    with _serving(nc_client, b"thumb") as _:
        nc_client.ensure_thumbnail(DAV, remote_mtime=1_700_000_000.0)

    conn = MagicMock()
    with patch.multiple(
        nc_client,
        _persistent_conn=MagicMock(return_value=conn),
        _conn=MagicMock(return_value=conn),
    ):
        assert nc_client.ensure_thumbnail(DAV, remote_mtime=1_700_000_000.0) is not None
    conn.request.assert_not_called()


@pytest.mark.parametrize("unknown", [None, 0.0])
def test_an_unknown_server_time_keeps_the_cached_copy(nc_client, unknown) -> None:
    """getlastmodified can be missing or unparseable (list_files falls back to
    0.0), and the lazy tile worker has no mtime at hand at all. Neither may turn
    into a re-download on every call."""
    with _serving(nc_client, b"thumb"):
        nc_client.ensure_thumbnail(DAV, remote_mtime=1_700_000_000.0)

    conn = MagicMock()
    with patch.multiple(
        nc_client,
        _persistent_conn=MagicMock(return_value=conn),
        _conn=MagicMock(return_value=conn),
    ):
        assert nc_client.ensure_thumbnail(DAV, remote_mtime=unknown) is not None
    conn.request.assert_not_called()


def test_a_cache_entry_from_before_stamping_is_kept(nc_client, tmp_path: Path) -> None:
    """Entries cached by an older Muga carry their download time, which is later
    than the server's mtime. Upgrading must not re-download the library."""
    with _serving(nc_client, b"thumb"):
        local = nc_client.ensure_thumbnail(DAV, remote_mtime=1_700_000_000.0)
    _touch(Path(local), 1_700_000_500.0)  # as if stamped by download time

    conn = MagicMock()
    with patch.multiple(
        nc_client,
        _persistent_conn=MagicMock(return_value=conn),
        _conn=MagicMock(return_value=conn),
    ):
        assert nc_client.ensure_thumbnail(DAV, remote_mtime=1_700_000_000.0) is not None
    conn.request.assert_not_called()


def test_a_replaced_original_is_downloaded_again(nc_client) -> None:
    """Same rule for the full-size cache the viewer reads from, not just the
    thumbnail."""
    with _serving(nc_client, b"old-original"):
        first = nc_client.download_file(DAV, remote_mtime=1_700_000_000.0)
    assert Path(first).read_bytes() == b"old-original"

    with _serving(nc_client, b"new-original"):
        second = nc_client.download_file(DAV, remote_mtime=1_700_000_900.0)

    assert second == first
    assert Path(second).read_bytes() == b"new-original"
