"""Guards for cached thumbnails and downloads going stale.

Both caches in this app key on a path alone: ``Thumbnailer.thumb_path_for``
hashes the local file path, and the Nextcloud client derives its cache names
from the DAV path. A photo edited in place — a rotation baked in by the viewer,
an EXIF write after a capture, an external editor, a file replaced on the
server — therefore keeps its cache filename, and a bare "does the cache file
exist?" test would serve the pre-edit image for as long as the photo keeps its
name.

The rule both caches now follow is the same: a cached file is stamped with its
*source's* modification time, so the two timestamps match while the cache entry
is current and the source's runs ahead the moment it is rewritten.

The comparison is deliberately one-directional (``>=``): entries written before
stamping existed carry their generation time, which is later than the source's,
so upgrading must not invalidate a whole library at once. The scanner covers the
other direction, because it compares against the mtime recorded in the index.
"""

from __future__ import annotations

import os
from pathlib import Path
from unittest.mock import MagicMock, patch

import pytest

import muga.thumbnails as thumbnails
from muga.thumbnails import Thumbnailer

PILImage = pytest.importorskip("PIL.Image")
nc = pytest.importorskip("muga.nextcloud")


LANDSCAPE = (40, 20)
PORTRAIT = (20, 40)


def _make_image(path: Path, size: tuple[int, int], color: tuple[int, int, int]) -> None:
    PILImage.new("RGB", size, color).save(str(path), "JPEG", quality=90)


def _touch(path: Path, mtime: float) -> None:
    """Set *path*'s mtime, leaving atime alone."""
    os.utime(path, (path.stat().st_atime, mtime))


def _shift_mtime(path: Path, seconds: float) -> None:
    """Move *path*'s mtime by *seconds*.

    Tests that depend on one file being newer than another say so explicitly
    rather than relying on two writes landing in different filesystem timestamp
    ticks — FAT on an SD card rounds to two seconds, and Muga runs on phones.
    """
    _touch(path, path.stat().st_mtime + seconds)


@pytest.fixture()
def thumbnailer(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Thumbnailer:
    monkeypatch.setattr(thumbnails, "THUMB_DIR", tmp_path / "thumbs")
    return Thumbnailer()


@pytest.fixture()
def photo(tmp_path: Path) -> Path:
    source = tmp_path / "photo.jpg"
    _make_image(source, LANDSCAPE, (200, 30, 30))
    return source


